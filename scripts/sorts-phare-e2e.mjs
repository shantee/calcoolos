import { chromium } from 'playwright';
const b = await chromium.launch({args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const p=await b.newPage({viewport:{width:1280,height:720},hasTouch:true,locale:'fr-FR',reducedMotion:'reduce'});
const errors=[];p.on('pageerror',e=>errors.push(e.message));
await p.goto((process.argv[2] ?? 'http://127.0.0.1:5181') + '/jeu/cubes-de-siege.html?niveau=cm2&calme');
await p.waitForFunction(()=>window.__siege);
await p.evaluate(()=>window.__siege.start('tranquille'));
await p.waitForFunction(()=>!window.__siege.busy() && window.__siege.enemyX()!==null && window.__siege.enemyX()<1149);
const tap=async(x,y)=>{const c=await p.locator('canvas').boundingBox();await p.touchscreen.tap(c.x+x*c.width/1280,c.y+y*c.height/720);await p.waitForTimeout(250)};
await tap(1118,650);
await tap(928,650);
const target=await p.evaluate(()=>window.__siege.session().round.puzzle);
if(target.solution.reduce((s,i)=>s+target.cubes[i],0)!==target.target)throw Error('solution');
await tap(738,650);
const x=await p.evaluate(()=>window.__siege.enemyX());
await p.waitForTimeout(7500);
const frozen=await p.evaluate(()=>window.__siege.enemyX());
console.log({x,frozen,bonus:await p.evaluate(()=>window.__siege.bonus())});
if(Math.abs(x-frozen)>1)throw Error('gel trop court');
await p.waitForTimeout(1300);
const thaw=await p.evaluate(()=>window.__siege.enemyX());
if(thaw>=frozen)throw Error('gel ne finit pas');
await p.screenshot({path:'/tmp/phare-sorts.png'});
console.log({target:target.target,x,frozen,thaw,errors});
await b.close();
if(errors.length)process.exitCode=1;
